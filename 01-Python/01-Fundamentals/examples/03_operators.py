"""Lesson 3: Arithmetic, comparison and logical operators."""

a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

print("Greater than:", a > b)
print("Equal:", a == b)
print("Both conditions:", a > 5 and b < 5)
